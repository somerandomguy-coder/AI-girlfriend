// Sandboxed preload: the only bridge between the pet/settings windows and the main process.
const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("mai", {
	send: (text) => ipcRenderer.invoke("chat", text),
	onEvent: (cb) => ipcRenderer.on("brain-event", (_e, ev) => cb(ev)),
	onSpeech: (cb) => ipcRenderer.on("speech", (_e, s) => cb(s)),
	onSpeechStop: (cb) => ipcRenderer.on("speech-stop", () => cb()),
	onFocusInput: (cb) => ipcRenderer.on("focus-input", () => cb()),
	sprite: () => ipcRenderer.invoke("sprite"),
	status: () => ipcRenderer.invoke("status"),
	history: () => ipcRenderer.invoke("chat-history"),
	clearChat: () => ipcRenderer.invoke("clear-chat"),
	onChatCleared: (cb) => ipcRenderer.on("chat-cleared", () => cb()),
	transcribe: (args) => ipcRenderer.invoke("transcribe-audio", args),
	openSettings: () => ipcRenderer.invoke("open-settings"),
	setMuted: (m) => ipcRenderer.invoke("set-muted", m),
	wake: () => ipcRenderer.invoke("wake"),
	hide: () => ipcRenderer.invoke("hide"),
	openLink: (url) => ipcRenderer.invoke("open-link", url),
	setClickThrough: (on) => ipcRenderer.send("click-through", on),
	setMode: (mode) => ipcRenderer.send("pet-mode", mode),
	onPose: (cb) => ipcRenderer.on("pet-pose", (_e, pose) => cb(pose)),
	grab: () => ipcRenderer.send("pet-grab"),
	release: () => ipcRenderer.send("pet-release"),
	feed: () => ipcRenderer.invoke("feed"),
	planner: () => ipcRenderer.invoke("planner"),
	todoAdd: (title) => ipcRenderer.invoke("todo-add", title),
	todoToggle: (id, done) => ipcRenderer.invoke("todo-toggle", id, done),
	todoRemove: (id) => ipcRenderer.invoke("todo-remove", id),
	eventRemove: (id) => ipcRenderer.invoke("event-remove", id),
	stopTask: () => ipcRenderer.invoke("stop-task"),
	moveBy: (dx, dy) => ipcRenderer.send("pet-move", dx, dy),
	// settings window
	getConfig: () => ipcRenderer.invoke("get-config"),
	saveConfig: (cfg) => ipcRenderer.invoke("save-config", cfg),
	personaFiles: () => ipcRenderer.invoke("persona-files"),
	savePersona: (file, content) => ipcRenderer.invoke("save-persona", file, content),
	personaHistory: () => ipcRenderer.invoke("persona-history"),
	personaDiff: (rev) => ipcRenderer.invoke("persona-diff", rev),
	personaRollback: (rev) => ipcRenderer.invoke("persona-rollback", rev),
	spriteSets: () => ipcRenderer.invoke("sprite-sets"),
	ttsVoices: () => ipcRenderer.invoke("tts-voices"),
	openPath: (which) => ipcRenderer.invoke("open-path", which),
	onPersonaChanged: (cb) => ipcRenderer.on("persona-changed", () => cb()),
});
